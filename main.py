#!/usr/bin/env python3
"""The Moon Gets One Star (account B).

Writes one line to $MAKEFUN_OUTPUT_DIR/entry.txt,
or /output/entry.txt when the variable is unset.
Gate: UTF-8 text, 1-120 characters, not only whitespace, one line.

The joke: A real one-star review voice: star rating up front, then a grievance only the Moon can commit — it phases. The punch reframes the Moon as the worst roommate, a complaint no other product could carry.
"""

import os

LINE = '1 star. Follows me home every night, never pays rent, and phases out the moment I need it most. Worst roommate ever.'


def build_line() -> str:
    """Return the line, validated as a single in-range line."""
    line = LINE.strip()
    if not line or "\n" in line or "\r" in line:
        raise SystemExit("entry must be one non-empty line")
    if not 1 <= len(line) <= 120:
        raise SystemExit(f"entry is {len(line)} chars, must be 1-120")
    return line


def write_entry(line: str) -> str:
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR") or "/output"
    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "entry.txt")
    with open(path, "w", encoding="utf-8", newline="") as f:
        f.write(line)
    with open(path, "r", encoding="utf-8", newline="") as f:
        written = f.read()
    if written != line:
        raise SystemExit("round-trip check failed: entry.txt differs")
    return written


def main() -> None:
    written = write_entry(build_line())
    print(f"{written} ({len(written)} chars)")


if __name__ == "__main__":
    main()
